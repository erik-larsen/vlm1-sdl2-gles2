#!/usr/bin/env python3
"""Extract waveform source data from the reconstructed VLM source.

- sines.s: the `sines` byte table (256-entry signed sine + extra 16-bit
  waveform data used by GPU modules).
- vlm.s `rantab`: the random-seed byte table (noise waveform).

Emits src/waves_data.c/.h. The five runtime tables (p_sines, p_saw,
p_square, p_ramp, p_rect) are derived from these at init by
src/waves.c, mirroring `startup` (vlm.s:1955-2001).

Usage: python3 scripts/extract_waves.py [path-to-vlm-ref]
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
VLM_REF = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO.parent / "vlm-ref"

DCB_RE = re.compile(r"^\s*dc\.b\s+(.*)$")
LABEL_RE = re.compile(r"^(\w+):")


def parse_dcb_ops(operands: str, out: bytearray, where: str) -> None:
    for tok in operands.split(";", 1)[0].split(","):
        tok = tok.strip()
        if not tok:
            continue
        m = re.match(r"^\$([0-9A-Fa-f]{1,2})$", tok)
        if not m:
            sys.exit(f"{where}: unexpected operand {tok!r}")
        out.append(int(m.group(1), 16))


def parse_file_bytes(path: Path) -> bytes:
    data = bytearray()
    for lineno, line in enumerate(path.read_text().splitlines(), 1):
        m = DCB_RE.match(line)
        if m:
            parse_dcb_ops(m.group(1), data, f"{path}:{lineno}")
    return bytes(data)


def parse_block_after_label(path: Path, label: str) -> bytes:
    data = bytearray()
    in_block = False
    for lineno, line in enumerate(path.read_text().splitlines(), 1):
        lm = LABEL_RE.match(line)
        if lm:
            if in_block:
                break
            in_block = lm.group(1) == label
            if in_block:
                line = line[len(label) + 1:]
        if in_block:
            m = DCB_RE.match(line)
            if m:
                parse_dcb_ops(m.group(1), data, f"{path}:{lineno}")
    if not data:
        sys.exit(f"label {label} not found or empty in {path}")
    return bytes(data)


def emit_array(name: str, data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ",".join(f"0x{b:02X}" for b in data[i:i + 16])
                     + ",")
    body = "\n".join(lines)
    return (f"const uint8_t {name}[{len(data)}] = {{\n{body}\n}};\n")


def main() -> None:
    sines = parse_file_bytes(VLM_REF / "src" / "vlm" / "sines.s")
    rantab = parse_block_after_label(VLM_REF / "src" / "vlm" / "vlm.s",
                                     "rantab")
    if len(sines) < 256:
        sys.exit(f"sines table too short: {len(sines)}")
    if len(rantab) < 257:
        sys.exit(f"rantab too short for 257-entry lookup: {len(rantab)}")

    (REPO / "src" / "waves_data.h").write_text(
        f"""/* Generated by scripts/extract_waves.py — do not edit. */
#ifndef VLM_WAVES_DATA_H
#define VLM_WAVES_DATA_H

#include <stdint.h>

#define VLM_SINES_RAW_SIZE {len(sines)}
#define VLM_RANTAB_SIZE {len(rantab)}

/* Raw `sines` data from sines.s: 256 signed sine bytes followed by
 * 16-bit waveform data consumed by GPU modules. */
extern const uint8_t vlm_sines_raw[VLM_SINES_RAW_SIZE];

/* `rantab` random-seed table (vlm.s:7394) — the noise waveform. */
extern const uint8_t vlm_rantab[VLM_RANTAB_SIZE];

#endif
""")
    (REPO / "src" / "waves_data.c").write_text(
        "/* Generated by scripts/extract_waves.py — do not edit. */\n"
        '#include "waves_data.h"\n\n'
        + emit_array("vlm_sines_raw", sines) + "\n"
        + emit_array("vlm_rantab", rantab))
    print(f"sines: {len(sines)} bytes, rantab: {len(rantab)} bytes")


if __name__ == "__main__":
    main()
