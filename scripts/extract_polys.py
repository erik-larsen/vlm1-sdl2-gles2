#!/usr/bin/env python3
"""Extract the gamma polygon objects (polyos) from images.s.

Each object: header {n.w, cx.w, cy.w}, n 16-byte face records
{colour.w, 3 x (vertex_index.w, intensity_code.w), pad.w}, then the
(x.w, y.w) vertex table. Kept as big-endian byte images; gamma parses
them with vlm_be16. polyos[0] is vlmlogo2 (a CRY image, not polygon
data) and is emitted as NULL.

Usage: python3 scripts/extract_polys.py [path-to-vlm-ref]
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
VLM_REF = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO.parent / "vlm-ref"
SRC = VLM_REF / "src" / "vlm" / "images.s"

ORDER = [None, "chev1", "chev", "square", "chev2", "chev3", "chev4", "chev5"]


def parse_blocks(text: str) -> dict:
    blocks = {}
    label = None
    for line in text.splitlines():
        m = re.match(r"^(\w+):", line)
        if m:
            label = m.group(1)
            blocks[label] = bytearray()
            line = line[len(label) + 1:]
        dm = re.search(r"dc\.b\s+(.*)", line)
        if dm and label:
            for tok in dm.group(1).split(";", 1)[0].split(","):
                tok = tok.strip()
                if tok:
                    blocks[label] += bytes([int(tok.lstrip("$"), 16)])
    return blocks


def main() -> None:
    blocks = parse_blocks(SRC.read_text())
    out_c = ["/* Generated by scripts/extract_polys.py — do not edit. */",
             '#include "polys_data.h"', ""]
    for name in ORDER:
        if name is None:
            continue
        data = blocks[name]
        rows = []
        for i in range(0, len(data), 16):
            rows.append("    " + ",".join(f"0x{b:02X}" for b in data[i:i+16])
                        + ",")
        out_c.append(f"static const uint8_t poly_{name}[{len(data)}] = {{")
        out_c.extend(rows)
        out_c.append("};\n")
    entries = ", ".join("NULL" if n is None else f"poly_{n}" for n in ORDER)
    out_c.append(f"const uint8_t *const vlm_polyos[8] = {{{entries}}};")
    (REPO / "src" / "polys_data.c").write_text("\n".join(out_c) + "\n")
    (REPO / "src" / "polys_data.h").write_text(
        """/* Generated by scripts/extract_polys.py — do not edit. */
#ifndef VLM_POLYS_DATA_H
#define VLM_POLYS_DATA_H

#include <stddef.h>
#include <stdint.h>

/* polyos table (images.s:24): big-endian polygon objects for gamma.
 * Entry 0 (vlmlogo2, a CRY image) is NULL. */
extern const uint8_t *const vlm_polyos[8];

#endif
""")
    sizes = {n: len(blocks[n]) for n in ORDER if n}
    print("extracted:", sizes)


if __name__ == "__main__":
    main()
