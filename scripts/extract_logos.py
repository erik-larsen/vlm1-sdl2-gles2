#!/usr/bin/env python3
"""Extract the 1-bit logo bitmaps used by delta modes 0/1 and the
splash overlay: jlogo2.cry and jaglogo.cry (header {w.w in 32px longs,
h.w} + rows; jlogo2 rows are w*4 bytes, jaglogo is displayed as a
5-phrase OP object so its rows are 40 bytes). Emits src/logos_data.c/.h
as raw big-endian byte images. bmobj[2]/[3] (blokk) is a 4-byte header
into unrelated ROM data, unused by presets — emitted as NULL.

Usage: python3 scripts/extract_logos.py [path-to-vlm-ref]
"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
VLM_REF = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO.parent / "vlm-ref"
IMG = VLM_REF / "src" / "vlm" / "images"


def emit(name: str, data: bytes) -> str:
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ",".join(f"0x{b:02X}" for b in data[i:i+16])
                    + ",")
    return (f"const uint8_t vlm_{name}[{len(data)}] = {{\n"
            + "\n".join(rows) + "\n};\n")


def main() -> None:
    jlogo2 = (IMG / "jlogo2.cry").read_bytes()
    jaglogo = (IMG / "jaglogo.cry").read_bytes()
    (REPO / "src" / "logos_data.c").write_text(
        "/* Generated by scripts/extract_logos.py — do not edit. */\n"
        '#include "logos_data.h"\n\n'
        + emit("jlogo2", jlogo2) + "\n" + emit("jaglogo", jaglogo))
    (REPO / "src" / "logos_data.h").write_text(
        f"""/* Generated by scripts/extract_logos.py — do not edit. */
#ifndef VLM_LOGOS_DATA_H
#define VLM_LOGOS_DATA_H

#include <stdint.h>

/* 1-bit logo bitmaps: header {{w.w (32px longs), h.w}} then rows.
 * jlogo2 = bmobj[0] (delta logo-plasma source, 16-byte rows);
 * jaglogo = bmobj[1] and the splash OP overlay (40-byte rows). */
#define VLM_JLOGO2_SIZE {len(jlogo2)}
#define VLM_JAGLOGO_SIZE {len(jaglogo)}
extern const uint8_t vlm_jlogo2[VLM_JLOGO2_SIZE];
extern const uint8_t vlm_jaglogo[VLM_JAGLOGO_SIZE];

#endif
""")
    print(f"jlogo2 {len(jlogo2)} bytes, jaglogo {len(jaglogo)} bytes")


if __name__ == "__main__":
    main()
