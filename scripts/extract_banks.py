#!/usr/bin/env python3
"""Extract the VLM-1 bank data (av1 blob) from the reconstructed source.

Parses banks.s (pure `dc.b $XX,...` lines) from the mwenge/vlm reference
repo, prepends the 56-byte av1 header from vlm.s (bank count, end marker,
and the ten $0090xxxx bank-offset pseudo-pointers), and emits
src/banks_data.c/.h with the blob as a C byte array.

See docs/analysis-banks-data.md for the full format description.

Usage: python3 scripts/extract_banks.py [path-to-vlm-ref]
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
VLM_REF = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO.parent / "vlm-ref"
BANKS_S = VLM_REF / "src" / "vlm" / "banks.s"

EXPECTED_DATA_BYTES = 46800

# av1 header, verbatim from vlm.s:8536-8551 (big-endian byte image).
AV1_HEADER = bytes.fromhex("0000000A" "0090B69C" "00900038" "F4352AC6")
BANK_OFFSETS = [0x0200, 0x1856, 0x34A4, 0x4482, 0x5776,
                0x61D8, 0x75A6, 0x8806, 0x9A72, 0xA6B4]

DCB_RE = re.compile(r"^\s*dc\.b\s+(.*)$")
BYTE_RE = re.compile(r"^\$([0-9A-Fa-f]{2})$")


def parse_banks(path: Path) -> bytes:
    data = bytearray()
    for lineno, line in enumerate(path.read_text().splitlines(), 1):
        m = DCB_RE.match(line)
        if not m:
            continue
        operands = m.group(1).split(";", 1)[0]
        for tok in operands.split(","):
            tok = tok.strip()
            if not tok:
                continue
            bm = BYTE_RE.match(tok)
            if not bm:
                sys.exit(f"{path}:{lineno}: unexpected operand {tok!r}")
            data.append(int(bm.group(1), 16))
    return bytes(data)


def main() -> None:
    data = parse_banks(BANKS_S)
    if len(data) != EXPECTED_DATA_BYTES:
        sys.exit(f"banks.s parsed to {len(data)} bytes, "
                 f"expected {EXPECTED_DATA_BYTES}")

    header = bytearray(AV1_HEADER)
    for off in BANK_OFFSETS:
        header += (0x00900000 | off).to_bytes(4, "big")
    blob = bytes(header) + data
    assert len(blob) == 56 + EXPECTED_DATA_BYTES

    out_c = REPO / "src" / "banks_data.c"
    out_h = REPO / "src" / "banks_data.h"

    lines = []
    for i in range(0, len(blob), 16):
        chunk = ",".join(f"0x{b:02X}" for b in blob[i:i + 16])
        lines.append(f"    {chunk},")
    body = "\n".join(lines)

    offs = ",".join(f"0x{o:04X}" for o in BANK_OFFSETS)
    out_h.write_text(f"""/* Generated by scripts/extract_banks.py — do not edit. */
#ifndef VLM_BANKS_DATA_H
#define VLM_BANKS_DATA_H

#include <stdint.h>

/* The av1 blob: 56-byte header + banks.s delta streams, big-endian
 * byte image exactly as laid out on the Jaguar. Bank offsets below are
 * relative to the start of this blob (the av1 label). */
#define VLM_AV1_SIZE {len(blob)}
#define VLM_NBANKS {len(BANK_OFFSETS)}

extern const uint8_t vlm_av1[VLM_AV1_SIZE];
extern const uint16_t vlm_bank_off[VLM_NBANKS];

#endif
""")
    out_c.write_text(f"""/* Generated by scripts/extract_banks.py — do not edit. */
#include "banks_data.h"

const uint16_t vlm_bank_off[VLM_NBANKS] = {{{offs}}};

const uint8_t vlm_av1[VLM_AV1_SIZE] = {{
{body}
}};
""")
    print(f"wrote {out_c} ({len(blob)} bytes) and {out_h}")


if __name__ == "__main__":
    main()
