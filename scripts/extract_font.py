#!/usr/bin/env python3
"""Extract myFont from font.s as a raw big-endian byte image:
4-byte header, 138 index words (char -> byte offset from myFont),
then 8-byte 8x8 1bpp glyphs. Emits src/font_data.c/.h.

Usage: python3 scripts/extract_font.py [path-to-vlm-ref]
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
VLM_REF = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO.parent / "vlm-ref"
SRC = VLM_REF / "src" / "vlm" / "font.s"


def main() -> None:
    data = bytearray()
    for line in SRC.read_text().splitlines():
        line = line.split(";", 1)[0]
        m = re.search(r"dc\.(l|w)\s+(.*)", line)
        if not m:
            continue
        size = 4 if m.group(1) == "l" else 2
        for tok in m.group(2).split(","):
            tok = tok.strip()
            if not tok:
                continue
            v = int(tok.lstrip("$"), 16) if tok.startswith("$") else int(tok)
            data += v.to_bytes(size, "big")
    (REPO / "src" / "font_data.c").write_text(
        "/* Generated by scripts/extract_font.py — do not edit. */\n"
        '#include "font_data.h"\n\n'
        f"const uint8_t vlm_font[{len(data)}] = {{\n"
        + "\n".join("    " + ",".join(f"0x{b:02X}" for b in data[i:i+16])
                    + "," for i in range(0, len(data), 16))
        + "\n};\n")
    (REPO / "src" / "font_data.h").write_text(
        f"""/* Generated by scripts/extract_font.py — do not edit. */
#ifndef VLM_FONT_DATA_H
#define VLM_FONT_DATA_H

#include <stdint.h>

/* myFont (font.s): 4-byte header, index words (char -> byte offset
 * from the table base), 8-byte 8x8 1bpp glyphs. */
#define VLM_FONT_SIZE {len(data)}
extern const uint8_t vlm_font[VLM_FONT_SIZE];

#endif
""")
    print(f"font: {len(data)} bytes")


if __name__ == "__main__":
    main()
