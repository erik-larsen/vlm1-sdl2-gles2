uint32_t cry_to_rgba[0x10000];

void cry_init(void)
{
    for (uint32_t i = 0; i < 0x10000; i++) {
        uint32_t cyan = (i >> 12) & 0x0F;
        uint32_t red = (i >> 8) & 0x0F;
        uint32_t y = i & 0xFF;
        /* TOM multiplies chroma by intensity: (c * y) >> 8 */
        uint32_t r = ((uint32_t)redcv[cyan][red] * y) >> 8;
        uint32_t g = ((uint32_t)greencv[cyan][red] * y) >> 8;
        uint32_t b = ((uint32_t)bluecv[cyan][red] * y) >> 8;
        /* RGBA8888 as bytes r,g,b,a == little-endian word 0xAABBGGRR */
        cry_to_rgba[i] = 0xFF000000u | (b << 16) | (g << 8) | r;
    }
}
